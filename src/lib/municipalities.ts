/** Where the admin page's "Tag older records" puts crews created before municipalities existed. */
export const PILOT_MUNICIPALITY_ID = 'ethekwini'

export function getMunicipality(id: string | null | undefined): Municipality | undefined {
  return MUNICIPALITIES.find((municipality) => municipality.id === id)
}

// Ray casting: count how many boundary edges a ray from the point crosses.
function isInside(lat: number, lng: number, boundary: [number, number][]): boolean {
  let inside = false
  for (let i = 0, j = boundary.length - 1; i < boundary.length; j = i++) {
    const [latI, lngI] = boundary[i]
    const [latJ, lngJ] = boundary[j]
    if (latI > lat !== latJ > lat && lng < ((lngJ - lngI) * (lat - latI)) / (latJ - latI) + lngI) inside = !inside
  }
  return inside
}

/**
 * Points this close outside a boundary still count as inside it. Covers the
 * simplified outline and phone GPS drift, and keeps beach reports (the
 * official boundary follows the shoreline) with the municipality.
 */
const EDGE_TOLERANCE_KM = 0.3

// Shortest distance from the point to any boundary edge, on a local flat
// projection (accurate enough over a few hundred metres).
function distanceToBoundaryKm(lat: number, lng: number, boundary: [number, number][]): number {
  const kmPerLat = 110.574
  const kmPerLng = 111.32 * Math.cos((lat * Math.PI) / 180)
  let nearest = Infinity
  for (let i = 0, j = boundary.length - 1; i < boundary.length; j = i++) {
    const ax = (boundary[j][1] - lng) * kmPerLng
    const ay = (boundary[j][0] - lat) * kmPerLat
    const bx = (boundary[i][1] - lng) * kmPerLng
    const by = (boundary[i][0] - lat) * kmPerLat
    const dx = bx - ax
    const dy = by - ay
    const lengthSquared = dx * dx + dy * dy
    const t = lengthSquared === 0 ? 0 : Math.max(0, Math.min(1, -(ax * dx + ay * dy) / lengthSquared))
    nearest = Math.min(nearest, Math.hypot(ax + t * dx, ay + t * dy))
  }
  return nearest
}

export function municipalityForPoint(lat?: number, lng?: number): string {
  if (lat === undefined || lng === undefined) return UNASSIGNED_MUNICIPALITY_ID
  const containing = MUNICIPALITIES.find((municipality) => isInside(lat, lng, municipality.boundary))
  if (containing) return containing.id
  let nearestId = UNASSIGNED_MUNICIPALITY_ID
  let nearestKm = EDGE_TOLERANCE_KM
  for (const municipality of MUNICIPALITIES) {
    const km = distanceToBoundaryKm(lat, lng, municipality.boundary)
    if (km <= nearestKm) {
      nearestKm = km
      nearestId = municipality.id
    }
  }
  return nearestId
}

/** Reports saved before tagging existed are placed by their GPS point instead. */
export function reportMunicipality(report: { municipalityId?: string; lat?: number; lng?: number }): string {
  return report.municipalityId ?? municipalityForPoint(report.lat, report.lng)
}
